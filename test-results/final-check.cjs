const { chromium } = require('C:/Users/hamorimo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  try {
    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
    const errors = []
    mobile.on('pageerror', (error) => errors.push(error.message))
    await mobile.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' })
    assert.equal(await mobile.locator('.people-sidebar').count(), 0)
    await mobile.getByRole('button', { name: 'Pessoas', exact: true }).click()
    await mobile.locator('.directory-person').filter({ has: mobile.getByText('Hudson', { exact: true }) }).click()
    assert.equal(await mobile.locator('.people-sidebar').count(), 0)
    await mobile.getByRole('button', { name: 'Adicionar integrante em Gestão', exact: true }).click()
    assert((await mobile.evaluate(() => JSON.parse(localStorage.getItem('ipcvt-planner-v2')))).teams[0].assignments.gestao.includes('hudson'))
    assert.deepEqual(errors, [])
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    console.log('PASS fresh mobile starts with clean canvas and touch selection closes directory')
    const desktop = await browser.newPage({ viewport: { width: 1440, height: 1050 } })
    await desktop.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' })
    await desktop.screenshot({ path: 'test-results/preview.png', fullPage: true })
    const blocked = await browser.newPage()
    await blocked.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('Blocked', 'SecurityError') } }))
    blocked.on('pageerror', (error) => errors.push(error.message))
    await blocked.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' })
    assert.equal(await blocked.locator('h1').count(), 1)
    assert.equal(await blocked.getByRole('alert').count(), 1)
    assert.deepEqual(errors, [])
    console.log('PASS disabled storage still opens board and displays save failure')
  } finally { await browser.close() }
})().catch((error) => { console.error(error); process.exitCode = 1 })
