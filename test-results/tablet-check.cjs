const { chromium } = require('C:/Users/hamorimo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const { pathToFileURL } = require('node:url')

;(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 768, height: 1024 } })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' })
    const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('ipcvt-planner-v2')))
    const before = await saved()
    const groups = await page.locator('.formation-board > .group-card').evaluateAll((cards) => cards.map((card) => { const b = card.getBoundingClientRect(); return { top: b.top, right: b.right, left: b.left } }))
    assert.equal(groups.length, 3)
    assert(groups.every((group) => Math.abs(group.top - groups[0].top) < 2))
    assert(groups.every((group) => group.right <= 768 && group.left >= 0))
    assert.equal(await page.locator('[data-role="soprano"] .person-token').count(), 4)
    await page.screenshot({ path: 'test-results/tablet-768-edit.png', fullPage: true })
    console.log('PASS portrait 768px shows all nuclei in one row and keeps all four existing sopranos')

    await page.getByRole('button', { name: 'Comparar times', exact: true }).click()
    assert.equal(await page.locator('.comparison-team').count(), 2)
    assert.equal(await page.getByLabel('Primeiro time', { exact: true }).inputValue(), 'time-a')
    assert.equal(await page.getByLabel('Segundo time', { exact: true }).inputValue(), 'time-b')
    assert.equal(await page.locator('[data-comparison-team="time-a"] [data-role="soprano"] .comparison-person').count(), 4)
    await page.getByLabel('Segundo time', { exact: true }).selectOption('time-c')
    await page.getByLabel('Primeiro time', { exact: true }).selectOption('time-b')
    assert.equal(await page.locator('.comparison-team').first().getAttribute('data-comparison-team'), 'time-b')
    assert.equal(await page.locator('.comparison-team').last().getAttribute('data-comparison-team'), 'time-c')
    assert.deepEqual(await saved(), before)
    await page.locator('.group-filters').getByRole('button', { name: 'Mídia', exact: true }).click()
    assert.equal(await page.locator('.comparison-group').count(), 2)
    await page.locator('.group-filters').getByRole('button', { name: 'Visão completa', exact: true }).click()
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Exportar planejamento em PDF', exact: true }).click()
    await (await downloadPromise).saveAs('test-results/tablet-compared.pdf')
    assert.equal(fs.readFileSync('test-results/tablet-compared.pdf').subarray(0, 5).toString(), '%PDF-')
    console.log('PASS comparison selection, per-nucleus filter, no data mutations and PDF download')

    await page.getByRole('button', { name: 'Editar Time C', exact: true }).click()
    assert.equal(await page.locator('.team-title').innerText(), 'Time C')
    for (const name of ['Hudson', 'Amanda', 'Arlete']) {
      await page.getByRole('button', { name: 'Exibir integrantes pela logo', exact: true }).click()
      await page.locator('.directory-person').filter({ has: page.locator('.directory-name', { hasText: new RegExp(`^${name}$`) }) }).click()
      assert.equal(await page.locator('.people-sidebar').count(), 0)
      await page.getByRole('button', { name: 'Adicionar integrante em Soprano', exact: true }).click()
    }
    assert.equal((await saved()).teams.find((team) => team.id === 'time-c').assignments.soprano.length, 3)
    assert.equal(await page.locator('[data-role="soprano"] .person-token').count(), 3)
    await page.getByRole('button', { name: 'Desfazer', exact: true }).click()
    assert.equal(await page.locator('[data-role="soprano"] .person-token').count(), 2)
    console.log('PASS direct editing, tablet drawer closes after selection, no two-person limit, undo')

    await page.getByRole('button', { name: 'Novo time', exact: true }).click()
    await page.getByRole('dialog').getByRole('textbox', { name: 'Nome', exact: true }).fill('Time D teste')
    await page.getByRole('button', { name: 'Criar time', exact: true }).click()
    await page.getByRole('button', { name: 'Comparar times', exact: true }).click()
    await page.keyboard.press('Control+z')
    await page.waitForTimeout(100)
    const teamIds = await page.locator('.comparison-team').evaluateAll((rows) => rows.map((row) => row.dataset.comparisonTeam))
    assert.equal(new Set(teamIds).size, 2)
    assert(!teamIds.some((id) => id.includes('teste')))
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.locator('.group-filters').getByRole('button', { name: 'Mídia', exact: true }).click()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    console.log('PASS comparison survives undo of selected team creation and keeps phone overflow local')

    const { createInitialState } = await import(pathToFileURL(process.cwd() + '/src/lib/planner.js'))
    const fixture = createInitialState()
    const source = fixture.teams[0].assignments
    fixture.teams[0].assignments = Object.fromEntries(Object.entries(source).map(([role, ids]) => [role, ids.slice(0, 2)]))
    fixture.teams[1].assignments = Object.fromEntries(Object.entries(source).map(([role, ids]) => [role, ids.slice(2, 4).length ? ids.slice(2, 4) : ids.slice(0, 1)]))
    const typical = await browser.newContext({ viewport: { width: 820, height: 1180 } })
    await typical.addInitScript((data) => localStorage.setItem('ipcvt-planner-v2', JSON.stringify(data)), fixture)
    const portrait = await typical.newPage()
    portrait.on('pageerror', (error) => errors.push(error.message))
    await portrait.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' })
    await portrait.getByRole('button', { name: 'Comparar times', exact: true }).click()
    await portrait.screenshot({ path: 'test-results/tablet-820-comparison-light.png', fullPage: true })
    const rowBounds = await portrait.locator('.comparison-team').evaluateAll((rows) => rows.map((row) => { const b = row.getBoundingClientRect(); return { top: b.top, height: b.height, bottom: b.bottom } }))
    assert.equal(await portrait.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    for (const row of await portrait.locator('.comparison-team').all()) {
      const tops = await row.locator('.comparison-group').evaluateAll((cards) => cards.map((card) => card.getBoundingClientRect().top))
      assert(tops.every((top) => Math.abs(top - tops[0]) < 2))
    }
    await portrait.getByRole('button', { name: 'Ativar modo escuro', exact: true }).click()
    await portrait.screenshot({ path: 'test-results/tablet-820-comparison-dark.png', fullPage: true })
    await portrait.setViewportSize({ width: 768, height: 1024 })
    await portrait.screenshot({ path: 'test-results/tablet-768-comparison.png', fullPage: true })
    assert.equal(await portrait.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.deepEqual(errors, [])
    console.log('PASS typical one/two-person teams at 820x1180 and 768x1024 in both themes', JSON.stringify(rowBounds))
    console.log('ALL TABLET CHECKS PASSED')
  } finally { await browser.close() }
})().catch((error) => { console.error(error); process.exitCode = 1 })
