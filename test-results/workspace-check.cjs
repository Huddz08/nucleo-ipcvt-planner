const { chromium } = require('C:/Users/hamorimo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')

;(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' })
    assert.equal(await page.locator('.navigation-rail, .people-sidebar, .calendar-view, .page-heading').count(), 0)
    assert.equal(await page.getByRole('button', { name: /Domingos|Modo foco|Sair do foco/ }).count(), 0)
    assert.equal(await page.locator('.role-box').count(), 17)
    assert.equal(await page.locator('.topbar').evaluate((el) => el.getBoundingClientRect().height), 52)
    assert.equal(await page.locator('.main-content').evaluate((el) => el.getBoundingClientRect().left), 0)
    assert.equal(await page.locator('.playbook-background svg').count(), 1)
    await page.screenshot({ path: 'test-results/workspace-light.png', fullPage: true })
    console.log('PASS canvas default, thin header, no calendar, pencil playbook background')

    await page.getByRole('button', { name: 'Exibir integrantes pela logo', exact: true }).click()
    assert.equal(await page.locator('.directory-person').count(), 33)
    await page.getByRole('button', { name: 'Ocultar integrantes pela logo', exact: true }).click()
    assert.equal(await page.locator('.people-sidebar').count(), 0)
    await page.getByRole('button', { name: 'Ativar modo escuro', exact: true }).click()
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark')
    await page.reload({ waitUntil: 'networkidle' })
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark')
    await page.screenshot({ path: 'test-results/workspace-dark.png', fullPage: true })
    await page.getByRole('button', { name: 'Exibir integrantes pela logo', exact: true }).click()
    await page.locator('.directory-person').filter({ has: page.getByText('Hudson', { exact: true }) }).dragTo(page.locator('[data-role="gestao"]'))
    let saved = await page.evaluate(() => JSON.parse(localStorage.getItem('ipcvt-planner-v2')))
    assert(saved.teams[0].assignments.gestao.includes('hudson'))
    assert(saved.teams[0].assignments.tenor.includes('hudson'))
    await page.getByRole('button', { name: 'Ocultar integrantes pela logo', exact: true }).click()
    console.log('PASS logo toggle, dark theme persists, drag-copy still works')

    await page.getByRole('button', { name: 'Editar grupos e funções', exact: true }).click()
    await page.screenshot({ path: 'test-results/workspace-dark-dialog.png' })
    await page.getByRole('button', { name: 'Fechar janela', exact: true }).click()
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Exportar planejamento em PDF', exact: true }).click()
    const download = await downloadPromise
    assert(download.suggestedFilename().endsWith('.pdf'))
    await download.saveAs('test-results/export-current.pdf')
    assert.equal(fs.readFileSync('test-results/export-current.pdf').subarray(0, 5).toString(), '%PDF-')
    console.log('PASS direct PDF download, not print dialog or JSON')

    await page.locator('.group-filters').getByRole('button', { name: 'Mídia', exact: true }).click()
    const filteredDownload = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Exportar planejamento em PDF', exact: true }).click()
    const filtered = await filteredDownload
    assert(filtered.suggestedFilename().includes('midia'))
    await filtered.saveAs('test-results/export-midia.pdf')
    await page.locator('.group-filters').getByRole('button', { name: 'Visão completa', exact: true }).click()
    await page.getByRole('button', { name: 'Opções do time', exact: true }).click()
    const allDownload = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Todos os times em PDF', exact: true }).click()
    await (await allDownload).saveAs('test-results/export-all.pdf')
    console.log('PASS PDF respects selected group and exports all teams from menu')

    await page.getByRole('button', { name: 'Opções do time', exact: true }).click()
    const backupPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Baixar backup (.json)', exact: true }).click()
    await (await backupPromise).saveAs('test-results/workspace-backup.json')
    assert.equal(JSON.parse(fs.readFileSync('test-results/workspace-backup.json', 'utf8')).version, 2)
    await page.getByRole('button', { name: 'Ativar modo claro', exact: true }).click()
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'light')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    console.log('PASS editable backup retained and switch back to light')

    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: 'Ativar modo escuro', exact: true }).click()
    await page.getByRole('button', { name: 'Exibir integrantes pela logo', exact: true }).click()
    await page.locator('.directory-person').filter({ has: page.getByText('Alexandre', { exact: true }) }).click()
    assert.equal(await page.locator('.people-sidebar').count(), 0)
    await page.getByRole('button', { name: 'Adicionar integrante em Gestão', exact: true }).click()
    await page.screenshot({ path: 'test-results/workspace-mobile-dark.png', fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.getByRole('button', { name: 'Ativar modo claro', exact: true }).click()
    await page.screenshot({ path: 'test-results/workspace-mobile-light.png', fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.deepEqual(errors, [])
    console.log('PASS mobile logo, touch assignment, both themes, no overflow or runtime errors')
    console.log('ALL WORKSPACE CHECKS PASSED')
  } finally { await browser.close() }
})().catch((error) => { console.error(error); process.exitCode = 1 })
